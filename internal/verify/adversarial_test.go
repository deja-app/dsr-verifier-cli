package verify_test

// adversarial_test.go — cross-type negative tests for receipt type enforcement.
//
// Each test proves that a receipt signed as type A cannot be presented as type B
// and pass signature verification. The mechanism is that each canonical form
// includes type-specific fields (and sometimes the "type" key itself), so the
// byte sequence signed for type A will never match the byte sequence constructed
// for type B.
//
// Design notes:
//
//   - All tests use a PINNED ed25519 key pair derived from a fixed 32-byte seed.
//     This eliminates ephemeral-key tautology risk: the key pair is stable across
//     runs and not generated by the test framework's entropy source.
//
//   - Envelopes carry the fields required by BOTH type A and type B, so that
//     dsr.CanonicalPayload succeeds for the claimed type B. The test then proves
//     the failure is a genuine signature mismatch, not a missing-field error.
//     For example, R1-L → R1: the envelope carries repository and pr_number so
//     attributionCanonical can run — but the signed bytes are still wrong.
//
//   - assertInvalid and dsrerrors are defined/imported in verify_test.go
//     (same package verify_test).

import (
	"bytes"
	"crypto/ed25519"
	"encoding/base64"
	"strings"
	"testing"

	"github.com/deja-app/dsr-verifier-cli/internal/dsr"
	dsrerrors "github.com/deja-app/dsr-verifier-cli/internal/errors"
	"github.com/deja-app/dsr-verifier-cli/internal/verify"
)

// ─── Pinned key helpers ───────────────────────────────────────────────────────

// pinnedEd25519Keys returns a deterministic ed25519 key pair from a fixed seed.
// The seed is 32 repeated 0x42 bytes; the pair is stable across all runs.
func pinnedEd25519Keys() (ed25519.PublicKey, ed25519.PrivateKey) {
	seed := bytes.Repeat([]byte{0x42}, ed25519.SeedSize)
	priv := ed25519.NewKeyFromSeed(seed)
	return priv.Public().(ed25519.PublicKey), priv
}

// pinnedProvidedKey wraps the pinned public key in a PublicKeyWithID so it
// can be passed directly to verify.Signature without going through file parsing.
func pinnedProvidedKey() *verify.PublicKeyWithID {
	pub, _ := pinnedEd25519Keys()
	return &verify.PublicKeyWithID{Key: pub}
}

// signPinned computes the canonical payload for e, signs it with the pinned
// ed25519 private key, and stores the base64 signature in e.Signature.
// SignatureAlgorithm is set to "ed25519-v1" before the canonical payload is
// computed, so canonical forms that include the signing_algorithm key (R1)
// will capture it correctly.
func signPinned(t *testing.T, e *dsr.Envelope) {
	t.Helper()
	_, priv := pinnedEd25519Keys()
	algo := dsr.AlgoED25519V1
	e.SignatureAlgorithm = &algo
	canonical, err := dsr.CanonicalPayload(e)
	if err != nil {
		t.Fatalf("signPinned: CanonicalPayload(%s) failed: %v", e.Type, err)
	}
	sig := ed25519.Sign(priv, []byte(canonical))
	e.Signature = base64.StdEncoding.EncodeToString(sig)
}

// ─── Envelope builders for adversarial tests ──────────────────────────────────
//
// Each builder returns an envelope that is valid for its own type AND carries
// the extra fields required by the cross-type claim. This lets the verification
// exercise the crypto path rather than short-circuiting on a missing-field error.

// adversarialR1L is a minimal R1-L envelope extended with R1-required fields
// (repository, pr_number, ccs_score, confidence, matched) so that switching
// its type to R1 allows attributionCanonical to run.
func adversarialR1L() *dsr.Envelope {
	issuedAt := "2026-07-17T00:00:00.000Z"
	count := int64(3)
	highest := "0.720"
	zone := "deja-test-zone"
	vault := "00000000-0000-0000-0000-000000000001"
	repo := "adversarial/test-repo"
	pr := int64(1)
	ccs := "0.7200"
	conf := "LOW"
	matched := "false"
	return &dsr.Envelope{
		DSRVersion:     "DSR/1.0",
		Type:           dsr.TypeR1L,
		ReceiptID:      "ADV-R1L-001",
		VaultID:        vault,
		Timestamp:      issuedAt,
		Actor:          "system:sde",
		Origin:         "production",
		Signature:      "placeholder",
		IssuedAt:       &issuedAt,
		CandidateCount: &count,
		HighestCcs:     &highest,
		ServiceZone:    &zone,
		// R1-required extras so type-B canonical construction succeeds:
		Repository: &repo,
		PRNumber:   &pr,
		CCSScore:   &ccs,
		Confidence: &conf,
		Matched:    &matched,
	}
}

