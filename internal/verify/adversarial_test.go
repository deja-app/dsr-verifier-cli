// ─── Cross-type negative pairs ────────────────────────────────────────────────
//
// Convention: TestAdversarial_CrossType_<SignedAs>_Claim<ClaimedAs>_Fails.
//
// Each test:
//   1. Builds and signs envelope A with the pinned key.
//   2. Shallow-copies A into envelope B, changing only the Type field.
//   3. Calls verify.Signature(B, pinnedProvidedKey()) and asserts Valid=false.
//
// The failure is always a genuine crypto mismatch: the canonical payload computed
// for type B differs from the bytes that were signed for type A.

// TestAdversarial_CrossType_R1L_ClaimR1_Fails proves that an R1-L receipt
// signed with lowConfidenceCanonical bytes cannot verify as an R1 receipt.
//
// R1-L canonical:   {candidate_count, highest_ccs, issued_at, receipt_id, service_zone, type:"R1-L", vault_id, version}
// R1 canonical:     {ccs_score, confidence, error_class, issued_at, matched, missing_field, pr_number, repository, service_zone}
//
// The byte sequences are completely different; the signature must fail.
func TestAdversarial_CrossType_R1L_ClaimR1_Fails(t *testing.T) {
	eA := adversarialR1L()
	signPinned(t, eA)

	eB := *eA // shallow copy — Type changes, Signature and other pointers stay
	eB.Type = dsr.TypeR1

	result := verify.Signature(&eB, pinnedProvidedKey())
	assertInvalid(t, "R1-L-signed receipt claimed as R1", result.Valid, result.Err, dsrerrors.SignatureInvalid)
}

